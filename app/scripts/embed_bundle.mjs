/* Embeds app/dist into the firmware: generates
 *   firmware/main/web_assets.c / web_assets.h / web_assets_manifest.json
 * Raw (uncompressed) bytes — total SPA is ~16 kB, no inflate dependency in
 * the static handler. CI runs --check after `npm run build` to verify the
 * committed embed matches a fresh build (hash check, issue #7 acceptance).
 *
 * Run from app/:  node scripts/embed_bundle.mjs [--check] */
import { readdirSync, readFileSync, writeFileSync, statSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const dist = new URL("../dist", import.meta.url).pathname;
const outDir = new URL("../../firmware/main", import.meta.url).pathname;
const check = process.argv.includes("--check");

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

function collect() {
  return walk(dist).map((abs) => {
    const bytes = readFileSync(abs);
    const rel = abs.slice(dist.length + 1).split(/[\\/]/).join("/");
    const path = rel === "index.html" ? "/" : "/" + rel;
    const dot = rel.lastIndexOf(".");
    const ext = dot >= 0 ? rel.slice(dot) : "";
    const mime = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css",
                   ".svg": "image/svg+xml", ".ico": "image/x-icon" }[ext] ?? "application/octet-stream";
    return {
      path, file: rel, bytes, mime,
      sha256: createHash("sha256").update(bytes).digest("hex"),
    };
  });
}

const assets = collect();
if (!assets.some((a) => a.path === "/")) {
  console.error("embed: dist/index.html missing — run npm run build first");
  process.exit(1);
}
assets.sort((a, b) => a.path.localeCompare(b.path));

const headerGuard = "GM_WEB_ASSETS_H";
const header = `/* GENERATED by app/scripts/embed_bundle.mjs — do not edit.
 * Dashboard SPA bundle embedded for the LAN HTTP server (issue #7). */
#ifndef ${headerGuard}
#define ${headerGuard}
#include <stddef.h>
#include <stdint.h>

typedef struct {
    const char *path;        /* URI path as served ("/", "/assets/x.js") */
    const char *mime;
    const uint8_t *data;
    size_t len;
} gm_web_asset_t;

extern const gm_web_asset_t gm_web_assets[];
extern const size_t gm_web_assets_count;

/* Returns the asset whose served path matches, or NULL. */
const gm_web_asset_t *gm_web_find(const char *path);

#endif /* ${headerGuard} */
`;

function toCArray(bytes, name) {
  const lines = [`static const uint8_t ${name}[${bytes.length}] = {`];
  for (let i = 0; i < bytes.length; i += 16) {
    const chunk = Array.from(bytes.slice(i, i + 16))
      .map((b) => `0x${b.toString(16).padStart(2, "0")}`).join(", ");
    lines.push("  " + chunk + ",");
  }
  lines.push("};");
  return lines.join("\n");
}

const tables = assets.map((a, i) => toCArray(a.bytes, `asset_${i}`)).join("\n\n");
const decls = assets.map((a, i) =>
  `  { "${a.path}", "${a.mime}", asset_${i}, ${a.bytes.length} },`).join("\n");
const body = `/* GENERATED by app/scripts/embed_bundle.mjs — do not edit. */
#include "web_assets.h"
#include <string.h>

${tables}

const gm_web_asset_t gm_web_assets[] = {
${decls}
};
const size_t gm_web_assets_count =
    sizeof(gm_web_assets) / sizeof(gm_web_assets[0]);

const gm_web_asset_t *gm_web_find(const char *path)
{
    for (size_t i = 0; i < gm_web_assets_count; i++)
        if (strcmp(gm_web_assets[i].path, path) == 0)
            return &gm_web_assets[i];
    return NULL;
}
`;

const manifest = {
  generator: "app/scripts/embed_bundle.mjs",
  file_count: assets.length,
  total_bytes: assets.reduce((s, a) => s + a.bytes.length, 0),
  files: assets.map(({ path, file, mime, bytes, sha256 }) =>
    ({ path, file, mime, bytes, sha256 })),
};

const filesToWrite = [
  ["web_assets.h", header],
  ["web_assets.c", body],
  ["web_assets_manifest.json", JSON.stringify(manifest, null, 2) + "\n"],
];

if (check) {
  let fail = 0;
  for (const [name, want] of filesToWrite) {
    let have = "";
    try { have = readFileSync(join(outDir, name), "utf8"); } catch { have = "<missing>"; }
    if (have !== want) {
      console.error(`EMBED CHECK FAIL: firmware/main/${name} is stale vs fresh dist`);
      fail = 1;
    }
  }
  const mPath = join(outDir, "web_assets_manifest.json");
  console.log(fail ? "" : `EMBED CHECK PASS — ${assets.length} assets, hashes match ${mPath}`);
  process.exit(fail);
}

mkdirSync(outDir, { recursive: true });
for (const [name, content] of filesToWrite) writeFileSync(join(outDir, name), content);
console.log(`embedded ${assets.length} assets (${manifest.total_bytes} B) -> firmware/main/`);
